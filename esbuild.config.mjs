import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/* THIS IS A GENERATED/BUNDLED FILE BY ESBUILD. If you want to view the source, visit the plugin's GitHub repo */`;

const prod = process.argv[2] === "production";

const common = {
	banner: { js: banner },
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
};

const mainCtx = await esbuild.context({ ...common, entryPoints: ["main.ts"], outfile: "main.js" });
// lib.js is evaluated via new Function(), so it must not require anything external.
const libCtx = await esbuild.context({
	...common,
	entryPoints: ["lib.ts"],
	outfile: "lib.js",
	external: [],
	platform: "browser",
	banner: {},
});

if (prod) {
	await Promise.all([mainCtx.rebuild(), libCtx.rebuild()]);
	process.exit(0);
} else {
	await Promise.all([mainCtx.watch(), libCtx.watch()]);
}
